// =====================================================
// List Pattern
// =====================================================

void main() {

  // List of fruits.
  var fruits = [
    "Apple",
    "Banana",
    "Mango",
  ];

  // Extract list values.
  var [first, second, third] = fruits;

  print("First: $first");
  print("Second: $second");
  print("Third: $third");
}