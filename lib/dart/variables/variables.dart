// main() is the starting point of a Dart program.
void main() {

  // ===================================================
  // 1. String Variable
  // ===================================================

  // String is used to store text.
  String name = "Flutter";

  // Print the value of the name variable.
  print(name);


  // ===================================================
  // 2. int Variable
  // ===================================================

  // int is used to store whole numbers.
  int age = 20;
  print(age);


  // ===================================================
  // 3. double Variable
  // ===================================================

  // double is used to store decimal numbers.
  double percentage = 85.5;
  print(percentage);


  // ===================================================
  // 4. bool Variable
  // ===================================================

  // bool stores either true or false.
  bool isStudent = true;
  print(isStudent);
}