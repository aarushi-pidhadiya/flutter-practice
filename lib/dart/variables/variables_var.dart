void main() {

  // var allows Dart to automatically determine the type.

  // Dart understands this as a String.
  var name = "Flutter";

  // Dart understands this as an int.
  var age = 20;

  // Dart understands this as a double.
  var percentage = 85.5;

  // Dart understands this as a bool.
  var isStudent = true;
  
  // Print all variables.
  print(name);
  print(age);
  print(percentage);
  print(isStudent);
}