void main() {

  // Create a variable.
  int number = 10;

  // Assignment (=)
  // Assigns a value to a variable.
  number = 20;

  print(number); // 20


  // Add and assign (+=)
  // Adds 5 to the current value.
  number += 5;

  print(number); // 25


  // Subtract and assign (-=)
  // Subtracts 5 from the current value.
  number -= 5;

  print(number); // 20


  // Multiply and assign (*=)
  // Multiplies the current value by 2.
  number *= 2;

  print(number); // 40


  // Divide and assign (/=)
  // Divides the current value by 2.
  number ~/= 2;

  print(number); // 20.0
}