void main() {

  int a = 10;
  int b = 20;

  // Equal to (==)
  // Checks whether two values are equal.
  print(a == b); // false

  // Not equal to (!=)
  // Checks whether two values are different.
  print(a != b); // true

  // Greater than (>)
  // Checks whether a is greater than b.
  print(a > b); // false

  // Less than (<)
  // Checks whether a is less than b.
  print(a < b); // true

  // Greater than or equal to (>=)
  print(a >= b); // false

  // Less than or equal to (<=)
  print(a <= b); // true
}