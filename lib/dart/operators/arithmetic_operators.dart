void main() {

  // Two numbers for our calculations.
  int a = 10;
  int b = 3;

  // Addition (+)
  // Adds two values.
  print(a + b); // 13

  // Subtraction (-)
  // Subtracts the second value from the first.
  print(a - b); // 7

  // Multiplication (*)
  // Multiplies two values.
  print(a * b); // 30

  // Division (/)
  // Divides one value by another.
  // The result is a double.
  print(a / b); // 3.333...

  // Integer Division (~/)
  // Divides and removes the decimal part.
  print(a ~/ b); // 3

  // Modulus (%)
  // Returns the remainder after division.
  print(a % b); // 1
}