void main() {

  int number = 10;

  // Increment (++)
  // Increases the value by 1.
  number++;

  print(number); // 11


  // Increment again.
  number++;

  print(number); // 12


  // Decrement (--)
  // Decreases the value by 1.
  number--;

  print(number); // 11


  // Decrement again.
  number--;

  print(number); // 10
}