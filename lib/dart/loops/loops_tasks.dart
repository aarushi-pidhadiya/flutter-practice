void main() {

  // ===================================================
  // TASK 1 — Multiplication Table
  // ===================================================

  int number = 5;

  // Print multiplication table of 5.
  for (int i = 1; i <= 10; i++) {

    print("$number x $i = ${number * i}");
  }


  // ===================================================
  // TASK 2 — Print Numbers from 1 to 20
  // ===================================================

  for (int i = 1; i <= 20; i++) {

    print(i);
  }


  // ===================================================
  // TASK 3 — Print Even Numbers
  // ===================================================

  for (int i = 2; i <= 20; i += 2) {

    print("Even: $i");
  }


  // ===================================================
  // TASK 4 — Print Odd Numbers
  // ===================================================

  for (int i = 1; i <= 20; i += 2) {

    print("Odd: $i");
  }


  // ===================================================
  // TASK 5 — Find Sum from 1 to 10
  // ===================================================

  int total = 0;

  for (int i = 1; i <= 10; i++) {

    total = total + i;
  }

  print("Total: $total");


  // ===================================================
  // TASK 6 — Print Numbers in Reverse
  // ===================================================

  for (int i = 10; i >= 1; i--) {

    print(i);
  }


  // ===================================================
  // TASK 7 — Multiplication Tables from 1 to 5
  // ===================================================

  for (int table = 1; table <= 5; table++) {

    print("Table of $table");

    for (int i = 1; i <= 10; i++) {

      print("$table x $i = ${table * i}");
    }

    print("----------------");
  }


  // ===================================================
  // TASK 8 — Count Even Numbers
  // ===================================================

  int count = 0;

  for (int i = 1; i <= 20; i++) {

    if (i % 2 == 0) {
      count++;
    }
  }

  print("Total Even Numbers: $count");


  // ===================================================
  // TASK 9 — Find Numbers Divisible by 5
  // ===================================================

  for (int i = 1; i <= 50; i++) {

    if (i % 5 == 0) {

      print("Divisible by 5: $i");
    }
  }


  // ===================================================
  // TASK 10 — Simple Star Pattern
  // ===================================================

  for (int i = 1; i <= 5; i++) {

    print("*" * i);
  }
}