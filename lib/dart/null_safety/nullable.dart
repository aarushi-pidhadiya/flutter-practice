// =====================================================
// Nullable Variables
// =====================================================

void main() {

  String? name;

  int? age;

  double? marks;


  // Nullable variables can contain null.

  name = "A Patel";

  age = 20;

  marks = 85.5;


  print(name);
  print(age);
  print(marks);


  // Assign null.

  name = null;

  age = null;

  marks = null;


  print(name);
  print(age);
  print(marks);
}