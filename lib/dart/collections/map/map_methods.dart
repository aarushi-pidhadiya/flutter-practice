void main() {

  // ===================================================
  // 1. Create a Map
  // ===================================================

  Map<String, dynamic> student = {
    "name": "A Patel",
    "age": 20,
    "course": "Flutter",
  };

  print(student);


  // ===================================================
  // 2. Access Value
  // ===================================================

  print(student["name"]);


  // ===================================================
  // 3. Add / Update Value
  // ===================================================

  student["city"] = "Rajkot";

  print(student);


  // ===================================================
  // 4. Remove
  // ===================================================

  student.remove("city");

  print(student);


  // ===================================================
  // 5. containsKey()
  // ===================================================

  print(student.containsKey("name"));


  // ===================================================
  // 6. containsValue()
  // ===================================================

  print(student.containsValue("Flutter"));


  // ===================================================
  // 7. length
  // ===================================================

  print(student.length);


  // ===================================================
  // 8. isEmpty
  // ===================================================

  print(student.isEmpty);


  // ===================================================
  // 9. isNotEmpty
  // ===================================================

  print(student.isNotEmpty);


  // ===================================================
  // 10. keys
  // ===================================================

  print(student.keys);


  // ===================================================
  // 11. values
  // ===================================================

  print(student.values);


  // ===================================================
  // 12. forEach()
  // ===================================================

  student.forEach((key, value) {

    print("$key : $value");
  });


  // ===================================================
  // 13. update()
  // ===================================================

  student.update(
    "age",
        (value) => value + 1,
  );

  print(student);


  // ===================================================
  // 14. putIfAbsent()
  // ===================================================

  student.putIfAbsent(
    "country",
        () => "India",
  );

  print(student);


  // ===================================================
  // 15. removeWhere()
  // ===================================================

  Map<String, int> marks = {
    "Math": 80,
    "English": 35,
    "Science": 75,
    "Computer": 30,
  };

  // Remove subjects where marks are below 40.
  marks.removeWhere(
        (subject, mark) => mark < 40,
  );

  print(marks);


  // ===================================================
  // 16. map()
  // ===================================================

  Map<String, int> numbers = {
    "a": 10,
    "b": 20,
    "c": 30,
  };

  // Create a new Map with doubled values.
  var doubled = numbers.map(
        (key, value) => MapEntry(
      key,
      value * 2,
    ),
  );

  print(doubled);


  // ===================================================
  // 17. addAll()
  // ===================================================

  student.addAll({
    "phone": "1234567890",
    "email": "test@gmail.com",
  });

  print(student);


  // ===================================================
  // 18. clear()
  // ===================================================

  Map<String, String> data = {
    "name": "Rahul",
    "city": "Rajkot",
  };

  data.clear();

  print(data);


  // ===================================================
  // 19. toString()
  // ===================================================

  print(student.toString());
}