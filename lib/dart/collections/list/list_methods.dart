void main() {

  // ===================================================
  // 1. add()
  // ===================================================

  List<String> names = ["Rahul", "Priya"];

  names.add("Amit");

  print(names);


  // ===================================================
  // 2. addAll()
  // ===================================================

  names.addAll(["Neha", "Karan"]);

  print(names);


  // ===================================================
  // 3. insert()
  // ===================================================

  names.insert(1, "Raj");

  print(names);


  // ===================================================
  // 4. insertAll()
  // ===================================================

  names.insertAll(2, ["Mehul", "Riya"]);

  print(names);


  // ===================================================
  // 5. remove()
  // ===================================================

  names.remove("Raj");

  print(names);


  // ===================================================
  // 6. removeAt()
  // ===================================================

  names.removeAt(0);

  print(names);


  // ===================================================
  // 7. removeLast()
  // ===================================================

  names.removeLast();

  print(names);


  // ===================================================
  // 8. removeWhere()
  // ===================================================

  List<int> numbers = [10, 20, 30, 40, 50];

  // Remove numbers greater than 30.
  numbers.removeWhere((number) => number > 30);

  print(numbers);


  // ===================================================
  // 9. retainWhere()
  // ===================================================

  numbers = [10, 20, 30, 40, 50];

  // Keep only numbers greater than 20.
  numbers.retainWhere((number) => number > 20);

  print(numbers);


  // ===================================================
  // 10. clear()
  // ===================================================

  numbers.clear();

  print(numbers);


  // ===================================================
  // 11. contains()
  // ===================================================

  List<int> marks = [50, 60, 70, 80];

  print(marks.contains(70));


  // ===================================================
  // 12. indexOf()
  // ===================================================

  print(marks.indexOf(70));


  // ===================================================
  // 13. lastIndexOf()
  // ===================================================

  List<int> values = [10, 20, 10, 30, 10];

  print(values.lastIndexOf(10));


  // ===================================================
  // 14. first
  // ===================================================

  print(marks.first);


  // ===================================================
  // 15. last
  // ===================================================

  print(marks.last);


  // ===================================================
  // 16. length
  // ===================================================

  print(marks.length);


  // ===================================================
  // 17. isEmpty
  // ===================================================

  print(marks.isEmpty);


  // ===================================================
  // 18. isNotEmpty
  // ===================================================

  print(marks.isNotEmpty);


  // ===================================================
  // 19. sort()
  // ===================================================

  List<int> numbers2 = [50, 10, 40, 20, 30];

  numbers2.sort();

  print(numbers2);


  // ===================================================
  // 20. reversed
  // ===================================================

  print(numbers2.reversed.toList());


  // ===================================================
  // 21. sublist()
  // ===================================================

  List<String> fruits = [
    "Apple",
    "Banana",
    "Mango",
    "Orange",
  ];

  // Get items from index 1 to 2.
  print(fruits.sublist(1, 3));


  // ===================================================
  // 22. getRange()
  // ===================================================

  print(fruits.getRange(1, 3).toList());


  // ===================================================
  // 23. forEach()
  // ===================================================

  fruits.forEach((fruit) {

    print(fruit);
  });


  // ===================================================
  // 24. where()
  // ===================================================

  List<int> nums = [10, 15, 20, 25, 30];

  // Get numbers greater than 20.
  var result = nums.where((number) => number > 20);

  print(result.toList());


  // ===================================================
  // 25. firstWhere()
  // ===================================================

  print(
    nums.firstWhere((number) => number > 20),
  );


  // ===================================================
  // 26. any()
  // ===================================================

  print(
    nums.any((number) => number > 25),
  );


  // ===================================================
  // 27. every()
  // ===================================================

  print(
    nums.every((number) => number > 5),
  );


  // ===================================================
  // 28. map()
  // ===================================================

  List<int> original = [1, 2, 3, 4, 5];

  // Multiply every number by 2.
  var doubled = original.map((number) => number * 2);

  print(doubled.toList());


  // ===================================================
  // 29. reduce()
  // ===================================================

  List<int> prices = [10, 20, 30];

  int total = prices.reduce(
        (a, b) => a + b,
  );

  print(total);


  // ===================================================
  // 30. fold()
  // ===================================================

  int total2 = prices.fold(
    100,
        (sum, price) => sum + price,
  );

  print(total2);


  // ===================================================
  // 31. join()
  // ===================================================

  List<String> words = [
    "Dart",
    "Flutter",
    "Developer",
  ];

  print(words.join(" "));


  // ===================================================
  // 32. expand()
  // ===================================================

  List<List<int>> list = [
    [1, 2],
    [3, 4],
  ];

  var expanded = list.expand((item) => item);

  print(expanded.toList());


  // ===================================================
  // 33. take()
  // ===================================================

  List<int> data = [10, 20, 30, 40, 50];

  // Take first 3 items.
  print(data.take(3).toList());


  // ===================================================
  // 34. skip()
  // ===================================================

  // Skip first 2 items.
  print(data.skip(2).toList());


  // ===================================================
  // 35. toSet()
  // ===================================================

  List<int> duplicateNumbers = [
    10,
    20,
    10,
    30,
    20,
  ];

  // Convert List to Set to remove duplicates.
  print(duplicateNumbers.toSet());


  // ===================================================
  // 36. toString()
  // ===================================================

  print(data.toString());
}