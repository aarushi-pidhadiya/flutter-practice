// =====================================================
// 1. Positional Record
// =====================================================

(String, int) student = (
"A Patel",
20,
);


// =====================================================
// 2. Named Record
// =====================================================

({String name, int age}) studentInfo = (
name: "A Patel",
age: 20,
);


// =====================================================
// Main Function
// =====================================================

void main() {

  // ===================================================
  // Positional Record
  // ===================================================

  print("Name: ${student.$1}");

  print("Age: ${student.$2}");


  print("");


  // ===================================================
  // Named Record
  // ===================================================

  print("Name: ${studentInfo.name}");

  print("Age: ${studentInfo.age}");
}