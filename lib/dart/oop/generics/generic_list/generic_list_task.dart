// =====================================================
// 1. Creating a Generic List
// =====================================================

List<String> fruits = [
  "Apple",
  "Banana",
  "Mango",
];


// =====================================================
// 2. Empty Generic List
// =====================================================

List<int> numbers = [];


// =====================================================
// 3. Adding Items
// =====================================================

void addItems() {

  numbers.add(10);
  numbers.add(20);
  numbers.add(30);

  print(numbers);
}


// =====================================================
// 4. Add Multiple Items
// =====================================================

void addMultipleItems() {

  numbers.addAll([
    40,
    50,
    60,
  ]);

  print(numbers);
}


// =====================================================
// 5. Accessing Items
// =====================================================

void accessItems() {

  print(fruits[0]);
  print(fruits[1]);
}


// =====================================================
// 6. Changing an Item
// =====================================================

void changeItem() {

  fruits[0] = "Orange";

  print(fruits);
}


// =====================================================
// 7. Length
// =====================================================

void showLength() {

  print("Length: ${fruits.length}");
}


// =====================================================
// 8. isEmpty
// =====================================================

void checkEmpty() {

  print("Is empty: ${fruits.isEmpty}");
}


// =====================================================
// 9. isNotEmpty
// =====================================================

void checkNotEmpty() {

  print("Is not empty: ${fruits.isNotEmpty}");
}


// =====================================================
// 10. contains()
// =====================================================

void checkContains() {

  print(fruits.contains("Mango"));
}


// =====================================================
// 11. indexOf()
// =====================================================

void findIndex() {

  print(fruits.indexOf("Mango"));
}


// =====================================================
// 12. remove()
// =====================================================

void removeItem() {

  fruits.remove("Banana");

  print(fruits);
}


// =====================================================
// 13. removeAt()
// =====================================================

void removeAtIndex() {

  fruits.removeAt(0);

  print(fruits);
}


// =====================================================
// 14. insert()
// =====================================================

void insertItem() {

  fruits.insert(0, "Apple");

  print(fruits);
}


// =====================================================
// 15. insertAll()
// =====================================================

void insertMultiple() {

  fruits.insertAll(
    1,
    [
      "Grapes",
      "Orange",
    ],
  );

  print(fruits);
}


// =====================================================
// 16. clear()
// =====================================================

void clearList() {

  fruits.clear();

  print(fruits);
}


// =====================================================
// 17. for-in Loop
// =====================================================

void usingForIn() {

  List<String> names = [
    "A",
    "B",
    "C",
  ];

  for (String name in names) {

    print(name);
  }
}


// =====================================================
// 18. forEach()
// =====================================================

void usingForEach() {

  fruits.forEach((fruit) {

    print(fruit);

  });
}


// =====================================================
// 19. first
// =====================================================

void getFirst() {

  print(fruits.first);
}


// =====================================================
// 20. last
// =====================================================

void getLast() {

  print(fruits.last);
}


// =====================================================
// 21. reversed
// =====================================================

void reverseList() {

  print(fruits.reversed.toList());
}


// =====================================================
// 22. Generic Function with List<T>
// =====================================================

void displayList<T>(List<T> items) {

  for (T item in items) {

    print(item);
  }
}


// =====================================================
// Main Function
// =====================================================

void main() {

  // ===================================================
  // String Generic List
  // ===================================================

  List<String> names = [
    "A Patel",
    "Rahul",
    "Priya",
  ];


  displayList<String>(names);


  print("");


  // ===================================================
  // Integer Generic List
  // ===================================================

  List<int> marks = [
    85,
    90,
    75,
  ];


  displayList<int>(marks);


  print("");


  // ===================================================
  // Double Generic List
  // ===================================================

  List<double> prices = [
    10.5,
    20.5,
    30.5,
  ];


  displayList<double>(prices);


  print("");


  // ===================================================
  // List Properties
  // ===================================================

  print("Length: ${names.length}");

  print("First: ${names.first}");

  print("Last: ${names.last}");

  print("Is Empty: ${names.isEmpty}");

  print("Is Not Empty: ${names.isNotEmpty}");

  print("Contains Rahul: ${names.contains("Rahul")}");

  print("Index of Priya: ${names.indexOf("Priya")}");
}