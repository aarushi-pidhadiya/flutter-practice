// =====================================================
// String List
// =====================================================

List<String> names = [
  "A Patel",
  "Rahul",
  "Priya",
];


// =====================================================
// Integer List
// =====================================================

List<int> numbers = [
  10,
  20,
  30,
];


// =====================================================
// Double List
// =====================================================

List<double> prices = [
  10.5,
  20.5,
  30.5,
];


// =====================================================
// Main Function
// =====================================================

void main() {

  // ===================================================
  // String List
  // ===================================================

  print("Names:");

  for (String name in names) {

    print(name);
  }


  print("");


  // ===================================================
  // Integer List
  // ===================================================

  print("Numbers:");

  for (int number in numbers) {

    print(number);
  }


  print("");


  // ===================================================
  // Double List
  // ===================================================

  print("Prices:");

  for (double price in prices) {

    print(price);
  }
}