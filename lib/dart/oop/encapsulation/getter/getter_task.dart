// =====================================================
// Student Class
// =====================================================

class Student {

  // ===================================================
  // Private Variables
  // ===================================================

  String _name;
  int _marks;


  // ===================================================
  // Constructor
  // ===================================================

  Student(
      this._name,
      this._marks,
      );


  // ===================================================
  // Getter for Name
  // ===================================================

  String get name {

    return _name;
  }


  // ===================================================
  // Getter for Marks
  // ===================================================

  int get marks {

    return _marks;
  }
}


// =====================================================
// Main Function
// =====================================================

void main() {

  // Create Student object.
  Student student = Student(
    "A Patel",
    85,
  );


  // ===================================================
  // Access private data using getters
  // ===================================================

  print("Name: ${student.name}");

  print("Marks: ${student.marks}");
}