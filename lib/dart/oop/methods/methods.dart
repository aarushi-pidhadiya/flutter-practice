// =====================================================
// Class
// =====================================================

class Student {

  // ===================================================
  // Properties
  // ===================================================

  String name;
  int age;
  String course;


  // ===================================================
  // Constructor
  // ===================================================

  Student(this.name, this.age, this.course);


  // ===================================================
  // Method 1
  // ===================================================

  // A method is a function inside a class.
  void sayHello() {

    print("Hello, my name is $name");
  }


  // ===================================================
  // Method 2
  // ===================================================

  void study() {

    print("$name is studying $course");
  }


  // ===================================================
  // Method 3
  // ===================================================

  void displayInfo() {

    print("Name: $name");
    print("Age: $age");
    print("Course: $course");
  }
}


// =====================================================
// Main Function
// =====================================================

void main() {

  // Create an object.
  Student student = Student(
    "A Patel",
    20,
    "Flutter",
  );


  // ===================================================
  // Call Methods
  // ===================================================

  student.sayHello();

  student.study();

  student.displayInfo();
}