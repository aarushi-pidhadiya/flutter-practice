class Mobile {

  // ===================================================
  // Properties
  // ===================================================

  String brand;
  double price;


  // ===================================================
  // Constructor
  // ===================================================

  // this.brand means:
  // brand property of the current object
  //
  // this.price means:
  // price property of the current object

  Mobile(this.brand, this.price);


  // ===================================================
  // Method
  // ===================================================

  void displayInfo() {

    print("Brand: $brand");
    print("Price: ₹$price");
  }
}


// =====================================================
// Main Function
// =====================================================

void main() {

  // ===================================================
  // Object 1
  // ===================================================

  Mobile mobile1 = Mobile(
    "Samsung",
    25000,
  );


  // ===================================================
  // Object 2
  // ===================================================

  Mobile mobile2 = Mobile(
    "Apple",
    60000,
  );


  // ===================================================
  // Display Information
  // ===================================================

  mobile1.displayInfo();

  print("");

  mobile2.displayInfo();
}